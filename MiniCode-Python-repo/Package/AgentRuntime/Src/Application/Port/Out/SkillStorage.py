"""Atomic, owner-scoped Skill state and version-bound package observations."""
from typing import Any, Callable, Protocol
from ...Dto.Skill import SkillDocument, SkillResource


class SkillLedger(Protocol):
    def read(self, owner: str) -> dict[str, Any]: ...
    def change(self, owner: str, operation: Callable[[dict], Any], *, event: str) -> Any: ...


class SkillSources(Protocol):
    def load(self, name: str) -> SkillDocument: ...
    def validate_resource(self, document: SkillDocument, path: str) -> Any: ...
    def resource(self, document: SkillDocument, path: str) -> SkillResource: ...
